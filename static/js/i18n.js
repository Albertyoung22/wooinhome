let currentLanguage = localStorage.getItem('wooinhome_lang') || 'zh-TW';

function setLanguage(lang) {
  if (!I18N_DICTIONARY[lang]) return;
  currentLanguage = lang;
  localStorage.setItem('wooinhome_lang', lang);

  // Update HTML lang attribute
  document.documentElement.lang = lang;

  // Update text nodes
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (I18N_DICTIONARY[lang][key]) {
      el.textContent = I18N_DICTIONARY[lang][key];
    }
  });

  // Update placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (I18N_DICTIONARY[lang][key]) {
      el.setAttribute('placeholder', I18N_DICTIONARY[lang][key]);
    }
  });

  // Update language selector active class
  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  // Dispatch custom event for dynamic components (calculator, ai_chat, etc.)
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

function t(key, defaultVal = '') {
  return (I18N_DICTIONARY[currentLanguage] && I18N_DICTIONARY[currentLanguage][key]) || defaultVal || key;
}

// Initialize on DOMContentLoaded
document.addEventListener('DOMContentLoaded', () => {
  setLanguage(currentLanguage);

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const lang = btn.getAttribute('data-lang');
      setLanguage(lang);
    });
  });
});

